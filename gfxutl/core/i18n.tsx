function initialLocale(): Locale {
  try {
    const saved = typeof localStorage === "undefined" ? null : localStorage.getItem("gfxutl:locale");
    if (saved === "ja" || saved === "en") return saved;
  } catch { /* Storage may be unavailable. */ }
  return typeof navigator !== "undefined" && !navigator.language.toLowerCase().startsWith("ja") ? "en" : "ja";
}

function interpolate(message: string, values?: Values) {
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (match, key: string) => values[key] === undefined ? match : String(values[key]));
}

let currentLocale: Locale = initialLocale();

export function translate(locale: Locale, key: string, values?: Values) {
  return interpolate(locale === "en" ? EN[key] ?? key : key, values);
}

export function translateCurrent(key: string, values?: Values) {
  return translate(currentLocale, key, values);
}

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, values?: Values) => string;
};

const I18nContext = createContext<I18nValue>({ locale: "ja", setLocale: () => {}, t: (key, values) => interpolate(key, values) });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(currentLocale);
  currentLocale = locale;
  const setLocale = (next: Locale) => {
    currentLocale = next;
    setLocaleState(next);
    try { localStorage.setItem("gfxutl:locale", next); } catch { /* Storage may be unavailable. */ }
  };
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, values) => translate(locale, key, values),
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
